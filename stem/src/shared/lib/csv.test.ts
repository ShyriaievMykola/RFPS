import { toCsv } from './csv';

describe('toCsv', () => {
  it('розділяє клітинки крапкою з комою, а дробову частину — комою', () => {
    expect(
      toCsv([
        ['Дата', 'кВт·год'],
        ['1 лист.', 12.5],
      ]),
    ).toBe('Дата;кВт·год\r\n1 лист.;12,5');
  });

  it('бере в лапки клітинки з роздільником, лапками чи переносом рядка', () => {
    expect(toCsv([['a;b', 'він сказав "так"', 'рядок\nдва']])).toBe(
      '"a;b";"він сказав ""так""";"рядок\nдва"',
    );
  });

  it('знешкоджує формули (CSV-ін’єкція)', () => {
    expect(toCsv([['=SUM(A1:A9)', '+1', '@cmd']])).toBe("'=SUM(A1:A9);'+1;'@cmd");
  });
});
